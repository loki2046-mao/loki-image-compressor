CREATE TABLE IF NOT EXISTS visitors (id TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS daily_visitors (day TEXT NOT NULL,id TEXT NOT NULL,PRIMARY KEY(day,id));
CREATE TABLE IF NOT EXISTS counts (day TEXT PRIMARY KEY,pv INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS events (id TEXT PRIMARY KEY,day TEXT NOT NULL,visitor TEXT NOT NULL);
CREATE TRIGGER IF NOT EXISTS record_visit AFTER INSERT ON events BEGIN
 INSERT OR IGNORE INTO visitors VALUES(NEW.visitor);
 INSERT OR IGNORE INTO daily_visitors VALUES(NEW.day,NEW.visitor);
 INSERT INTO counts(day,pv) VALUES(NEW.day,1) ON CONFLICT(day) DO UPDATE SET pv=pv+1;
END;
